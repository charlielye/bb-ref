//! B5: the UltraKeccak flavor. Non-ZK proofs, VKs and vk_hashes are byte-equal to
//! `bb prove --scheme ultra_honk --oracle_hash keccak --disable_zk --write_vk`; bb's ZK proofs
//! verify (fixtures under `keccak/`, produced by `tools/regen/regen_backend.sh`).

mod common;
use bb_ref::acir::format::{decode_program, decode_witness};
use bb_ref::acir::lower::build_circuit;
use bb_ref::base::{CommitmentKey, Fr, KeccakBn254, OsRng, U256};
use bb_ref::base::srs::bn254_g2;
use bb_ref::base::vk::Vk;
use bb_ref::honk::prover_instance::ProverInstance;
use bb_ref::honk::ultra_prover::prove_ultra_as;
use bb_ref::honk::ultra_verifier::verify_ultra_keccak;
use bb_ref::honk::{ULTRA_KECCAK, ULTRA_KECCAK_ZK};

const PROGRAMS: [&str; 3] = ["a_1_mul", "array_dynamic", "unsafe_range_constraint"];

fn read_words(path: &std::path::Path) -> Vec<U256> {
    let bytes = std::fs::read(path).unwrap_or_else(|_| panic!("missing {path:?}"));
    if bytes.is_empty() {
        return vec![];
    }
    assert_eq!(bytes.len() % 32, 0, "bad word file length");
    bytes
        .chunks(32)
        .map(|c| {
            let mut limbs = [0u64; 4];
            for (i, l) in c.chunks(8).enumerate() {
                limbs[3 - i] = u64::from_be_bytes(l.try_into().unwrap());
            }
            U256::new(limbs)
        })
        .collect()
}

fn words_to_frs(words: &[U256]) -> Vec<Fr> {
    use bb_ref::base::codec::Transcriptable;
    words.iter().map(|w| <Fr as Transcriptable<U256>>::from_fields(&[*w])).collect()
}

fn build(dir: &std::path::Path) -> ProverInstance {
    let circuit = decode_program(&std::fs::read(dir.join("program.json")).expect("program.json"));
    let witness = decode_witness(&std::fs::read(dir.join("witness.gz")).expect("witness.gz"), &mut OsRng);
    let mut builder = build_circuit(&circuit, Some(&witness));
    assert!(builder.failed.is_none(), "builder failure: {:?}", builder.failed);
    ProverInstance::from_builder(&ULTRA_KECCAK, &mut builder, &mut OsRng)
}

fn keccak_vk(inst: &ProverInstance, ck: &CommitmentKey) -> Vk<KeccakBn254> {
    let vk = inst.compute_vk(ck);
    Vk::<KeccakBn254> {
        log_circuit_size: vk.log_circuit_size,
        num_public_inputs: vk.num_public_inputs,
        pub_inputs_offset: vk.pub_inputs_offset,
        comms: vk.comms,
    }
}

#[test]
fn keccak_nozk_byte_exact() {
    for prog in PROGRAMS {
        let dir = common::fixture_dir(&format!("keccak/{prog}"));
        if !dir.join("proof").exists() {
            eprintln!("skipping {prog}: no fixture");
            continue;
        }
        let mut inst = build(&dir);
        let ck = CommitmentKey::new(inst.max_end_index);
        let vk = keccak_vk(&inst, &ck);
        assert_eq!(
            vk.to_bytes(),
            std::fs::read(dir.join("vk")).unwrap(),
            "{prog}: vk bytes"
        );
        let hash_bytes: Vec<u8> = bb_ref::base::keccak::u256_to_bytes_be(&vk.hash()).to_vec();
        assert_eq!(
            hash_bytes,
            std::fs::read(dir.join("vk_hash")).unwrap(),
            "{prog}: vk_hash"
        );
        let user_pis = read_words(&dir.join("public_inputs"));
        let proof = prove_ultra_as::<KeccakBn254>(&mut inst, &vk, &mut OsRng);
        let bb_proof = read_words(&dir.join("proof"));
        let mine = &proof[user_pis.len()..];
        assert_eq!(mine.len(), bb_proof.len(), "{prog}: proof length");
        if let Some(i) = mine.iter().zip(&bb_proof).position(|(a, b)| a != b) {
            panic!("{prog}: proof differs at word {i}: {:?} vs {:?}", mine[i], bb_proof[i]);
        }
        assert!(
            verify_ultra_keccak(&ULTRA_KECCAK, &vk, &words_to_frs(&user_pis), &bb_proof, &bn254_g2()),
            "{prog}: verify"
        );
        println!("{prog}: keccak non-ZK proof, VK and vk_hash byte-equal");
    }
}

/// B6: the real-witness `rollup_root` — keccak transcript, ROOT_ROLLUP recursion, full in-circuit
/// IPA — proof/VK/vk_hash byte-equal to a seeded `bb prove --oracle_hash keccak` golden
/// (`instance/backend/rollup_root/seeded`, regenerated by tools/regen/regen_backend.sh). Draws are
/// seed-deterministic on both sides (DebugRng mirrors bb's BB_RNG_SEED engine).
#[test]
fn rollup_root_witness_byte_exact() {
    let dir = common::fixture_dir("backend/rollup_root");
    let golden = common::fixture_dir("instance/backend/rollup_root/seeded");
    if !golden.join("proof").exists() {
        eprintln!("skipping rollup_root witness: no seeded golden");
        return;
    }
    bb_ref::base::rng::set_global(Box::new(bb_ref::base::rng::DebugRng::new(12345)));
    let mut rng = bb_ref::base::rng::GlobalProxy;
    let circuit = decode_program(&std::fs::read(dir.join("program.json")).expect("program.json"));
    let witness = decode_witness(&std::fs::read(dir.join("witness.gz")).expect("witness.gz"), &mut rng);
    let mut builder = bb_ref::acir::lower::build_circuit_opts(&circuit, Some(&witness), false);
    assert!(builder.failed.is_none(), "builder failure: {:?}", builder.failed);
    let mut inst = ProverInstance::from_builder(&ULTRA_KECCAK, &mut builder, &mut rng);
    let ck = CommitmentKey::new(inst.max_end_index);
    let vk = keccak_vk(&inst, &ck);
    assert_eq!(vk.to_bytes(), std::fs::read(golden.join("vk")).unwrap(), "rollup_root: vk bytes");
    let hash_bytes: Vec<u8> = bb_ref::base::keccak::u256_to_bytes_be(&vk.hash()).to_vec();
    assert_eq!(hash_bytes, std::fs::read(golden.join("vk_hash")).unwrap(), "rollup_root: vk_hash");
    let user_pis = read_words(&golden.join("public_inputs"));
    let proof = prove_ultra_as::<KeccakBn254>(&mut inst, &vk, &mut rng);
    let bb_proof = read_words(&golden.join("proof"));
    let mine = &proof[user_pis.len()..];
    assert_eq!(mine.len(), bb_proof.len(), "rollup_root: proof length");
    if let Some(i) = mine.iter().zip(&bb_proof).position(|(a, b)| a != b) {
        panic!("rollup_root: proof differs at word {i}: {:?} vs {:?}", mine[i], bb_proof[i]);
    }
    assert!(
        verify_ultra_keccak(&ULTRA_KECCAK, &vk, &words_to_frs(&user_pis), &bb_proof, &bn254_g2()),
        "rollup_root: verify"
    );
    println!("rollup_root: real-witness keccak proof, VK and vk_hash byte-equal");
}

#[test]
fn keccak_zk_verifies() {
    for prog in PROGRAMS {
        let dir = common::fixture_dir(&format!("keccak/{prog}_zk"));
        if !dir.join("proof").exists() {
            eprintln!("skipping {prog}_zk: no fixture");
            continue;
        }
        let vk_bytes = std::fs::read(dir.join("vk")).unwrap();
        let vk = Vk::<KeccakBn254>::from_bytes(&vk_bytes, ULTRA_KECCAK_ZK.layout().num_precomputed);
        let user_pis = read_words(&dir.join("public_inputs"));
        let proof = read_words(&dir.join("proof"));
        assert!(
            verify_ultra_keccak(&ULTRA_KECCAK_ZK, &vk, &words_to_frs(&user_pis), &proof, &bn254_g2()),
            "{prog}: zk verify"
        );
        println!("{prog}: bb keccak ZK proof verifies");
    }
}
